// PRD.md C.2 "Storage discipline": worker photos used to be unbounded base64 blobs inside a
// Postgres `text` column (worker_details.photo). This is the one place that reads/writes the
// real image files that replace it — every caller (userService.js, scripts/backfillPhotos.js)
// goes through here rather than touching `fs` directly, so the size cap, the magic-byte check,
// and the traversal guard can't be bypassed by a new call site.
import fs from 'fs';
import fsp from 'fs/promises';
import path from 'path';
import crypto from 'crypto';
import { AppError } from '../errors/AppError.js';
import { logger } from '../config/logger.js';

// Docker sets this to a named volume (see docker-compose.yml's `uploads` volume); local
// (non-Docker) dev defaults to a gitignored folder next to the rest of the backend source.
export const UPLOAD_DIR = path.resolve(process.env.UPLOAD_DIR || path.join(import.meta.dirname, '..', 'uploads'));

// Server-side cap for a NEW photo upload (client-resized to ~512px before it ever gets here —
// see frontend/src/utils/resizeImage.js). Deliberately smaller than the old 10mb body limit that
// covered this field: 512 KB is generous for a small square avatar and keeps the 200-worker list
// endpoint's worst case (if it ever re-added photos) in the tens of megabytes, not hundreds.
// scripts/backfillPhotos.js intentionally does NOT use this cap — see its own header comment.
export const MAX_PHOTO_BYTES = 512 * 1024;

// Keyed by the three types PhotoUpload.jsx's resizer can actually produce, plus the pre-existing
// magic-byte signature each format starts with — checked against the real decoded bytes, not
// just the data URL's own declared `image/...` string, so a mislabeled or corrupted upload can't
// sneak an arbitrary file extension onto disk.
const SIGNATURES = {
  'image/jpeg': { ext: 'jpg', magic: [0xff, 0xd8, 0xff] },
  'image/png': { ext: 'png', magic: [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a] },
  'image/webp': { ext: 'webp', magic: [0x52, 0x49, 0x46, 0x46] }, // 'RIFF'; WEBP tag follows at byte 8
};

const DATA_URL_RE = /^data:(image\/(?:jpeg|png|webp));base64,(.+)$/;

function matchesMagic(buf, magic) {
  if (buf.length < magic.length) return false;
  return magic.every((byte, i) => buf[i] === byte);
}

// Decodes and validates a `data:image/...;base64,...` string. Returns { buffer, ext }.
// Throws AppError(400, ...) on anything that isn't a well-formed, on-cap image of an allowed
// type — never partially trusts the caller's declared MIME type.
export function decodePhotoDataUrl(dataUrl, { maxBytes = MAX_PHOTO_BYTES } = {}) {
  if (typeof dataUrl !== 'string') {
    throw new AppError(400, 'photo must be a data URL string.');
  }
  const match = DATA_URL_RE.exec(dataUrl);
  if (!match) {
    throw new AppError(400, 'photo must be a data:image/(jpeg|png|webp);base64,... URL.');
  }
  const [, mime, base64] = match;
  const buffer = Buffer.from(base64, 'base64');
  if (buffer.length === 0) {
    throw new AppError(400, 'photo data is empty.');
  }
  if (buffer.length > maxBytes) {
    throw new AppError(400, `photo exceeds the ${Math.floor(maxBytes / 1024)}KB limit.`);
  }
  const sig = SIGNATURES[mime];
  if (!sig || !matchesMagic(buffer, sig.magic)) {
    throw new AppError(400, 'photo content does not match its declared image type.');
  }
  return { buffer, ext: sig.ext };
}

// mkdir -p, then a real write check (a mounted-but-unwritable volume, or a wrong permission on a
// fresh Docker named volume, should fail loudly at boot — the same "fail fast" shape as the
// SECRET_KEY check in app.js — rather than surfacing as a mysterious 500 on the first upload).
export async function ensureUploadDir() {
  await fsp.mkdir(UPLOAD_DIR, { recursive: true });
  const probe = path.join(UPLOAD_DIR, `.write-check-${process.pid}`);
  await fsp.writeFile(probe, '');
  await fsp.rm(probe);
}

// path.basename strips any directory component outright, and the resolved path is then checked
// to still be inside UPLOAD_DIR — belt-and-suspenders against a `photo_path` value that was
// never generated by savePhoto() in the first place (there's no code path that writes one today,
// but this is the one function every read goes through, so it's the right place for the guard).
export function resolvePhotoPath(name) {
  const resolved = path.resolve(UPLOAD_DIR, path.basename(name));
  if (resolved !== path.join(UPLOAD_DIR, path.basename(name)) || !resolved.startsWith(UPLOAD_DIR + path.sep)) {
    throw new AppError(400, 'Invalid photo reference.');
  }
  return resolved;
}

// Writes to a temp file in the same directory, then renames into place — rename is atomic on the
// same filesystem, so a reader can never observe a partially-written file. Returns the stored
// filename (what gets saved in worker_details.photo_path), not the full path.
export async function savePhoto(buffer, ext) {
  await ensureUploadDir();
  const filename = `${crypto.randomUUID()}.${ext}`;
  const finalPath = path.join(UPLOAD_DIR, filename);
  const tmpPath = `${finalPath}.tmp-${process.pid}-${Date.now()}`;
  await fsp.writeFile(tmpPath, buffer);
  await fsp.rename(tmpPath, finalPath);
  return filename;
}

// Best-effort delete: a missing file (already cleaned up, or never written) is not an error —
// callers use this for both "replace the old photo" and "roll back a half-finished write", and
// neither case should ever throw past this point. Any OTHER failure (permissions, disk error) is
// logged with the filename, per CLAUDE.md's "no raw objects, an event + an id" logging rule —
// via the shared base logger, not req.log: this util is called from both request-scoped code
// (services/userService.js) and a bare CLI script (scripts/backfillPhotos.js), neither of which
// can hand it a `req` to log through even if it wanted to.
export async function removePhoto(name) {
  if (!name) return;
  try {
    const full = resolvePhotoPath(name);
    await fsp.rm(full);
  } catch (e) {
    if (e.code === 'ENOENT') return;
    // `photoPath`, not `photo` — the latter is one of config/logger.js's redacted field names
    // (it means something different there: the legacy base64 column), and `name` here is just a
    // filename, exactly the thing worth seeing in the log.
    logger.error({ err: e, photoPath: name }, '[photoStorage] failed to remove photo');
  }
}

// Sync existence check for the serving route (res.sendFile needs a real, checked path — it
// doesn't itself distinguish "missing file" from other errors in a way that's safe to answer a
// generic 404 for without first checking).
export function photoExistsSync(name) {
  if (!name) return false;
  try {
    return fs.existsSync(resolvePhotoPath(name));
  } catch {
    return false;
  }
}

export default {
  UPLOAD_DIR,
  MAX_PHOTO_BYTES,
  decodePhotoDataUrl,
  ensureUploadDir,
  resolvePhotoPath,
  savePhoto,
  removePhoto,
  photoExistsSync,
};
